<?php
require_once '../config/config.php';
if (function_exists('requireLogin')) { requireLogin(); }
require_once __DIR__ . '/../includes/receipt-branding.php';

if (!isset($conn) || !($conn instanceof mysqli)) { die('Database connection not found.'); }
$conn->set_charset('utf8mb4');

$id = (int)($_GET['id'] ?? 0);
if ($id <= 0) { die('Invalid receipt ID.'); }

function fr_receipt_h($v){ return htmlspecialchars((string)$v, ENT_QUOTES, 'UTF-8'); }
function fr_receipt_money($n){ return 'UGX ' . number_format((float)$n, 0); }
function fr_find_autoload(){
    $paths = array(
        __DIR__ . '/../vendor/autoload.php',
        __DIR__ . '/../../vendor/autoload.php',
        dirname(__DIR__) . '/vendor/autoload.php',
        $_SERVER['DOCUMENT_ROOT'] . '/vendor/autoload.php'
    );
    foreach ($paths as $p) { if ($p && file_exists($p)) return $p; }
    return null;
}

