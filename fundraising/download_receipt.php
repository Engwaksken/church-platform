               m.full_name member_name, m.member_no, m.phone
        FROM fundraising_collections fc
        LEFT JOIN fundraising f ON f.id=fc.campaign_id
        LEFT JOIN members m ON m.id=fc.member_id
        WHERE fc.id=?";
$stmt = $conn->prepare($sql);
$stmt->bind_param('i', $id);
$stmt->execute();
$receipt = $stmt->get_result()->fetch_assoc();
$stmt->close();
if (!$receipt) { die('Receipt not found.'); }
receipt_clip_fields($receipt);

$autoload = fr_find_autoload();
if (!$autoload) { die('Dompdf autoload not found. Please install Dompdf using Composer and keep vendor/autoload.php available.'); }
require_once $autoload;

use Dompdf\Dompdf;
